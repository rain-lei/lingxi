"""Generate the GB2312 Han fallback font used by the LCD conversation UI.

Requires Pillow. Example:
    python generate_ui_cjk.py --font <NotoSansSC.ttf>

The generated font contains all 6,763 GB2312 Han characters, indexed by sorted
Unicode code point. Each 12 x 16 glyph occupies 24 bytes: continuous row-major
1-bit pixels, with the first pixel in the most significant bit. There is no
padding at the end of a row. The source font is licensed under SIL OFL 1.1;
see assets/NotoSansSC-OFL.txt.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


WIDTH = 12
HEIGHT = 16
BYTES_PER_GLYPH = WIDTH * HEIGHT // 8
EXPECTED_COUNT = 6763
SCALE = 3


def gb2312_han_codes() -> list[int]:
    """Enumerate GB2312 zones 16-87, omitting unassigned positions."""
    codes = set()
    for high in range(0xB0, 0xF8):
        for low in range(0xA1, 0xFF):
            try:
                char = bytes((high, low)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if len(char) != 1 or not 0x4E00 <= ord(char) <= 0x9FFF:
                raise ValueError(f"Unexpected GB2312 Han entry: {high:02x}{low:02x}")
            codes.add(ord(char))
    result = sorted(codes)
    if len(result) != EXPECTED_COUNT:
        raise ValueError(f"Expected {EXPECTED_COUNT} Han characters, got {len(result)}")
    return result


def pack_glyph(font: ImageFont.FreeTypeFont, code: int) -> bytes:
    canvas = Image.new("L", (WIDTH * SCALE, HEIGHT * SCALE), 0)
    # A shared baseline retains consistent placement across the whole charset.
    ImageDraw.Draw(canvas).text(
        (0, 13 * SCALE), chr(code), font=font, fill=255, anchor="ls"
    )
    raster = canvas.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)
    pixel_reader = getattr(raster, "get_flattened_data", raster.getdata)
    pixels = list(pixel_reader())
    packed = bytearray(BYTES_PER_GLYPH)
    for index, value in enumerate(pixels):
        if value >= 96:
            packed[index // 8] |= 0x80 >> (index % 8)
    if not any(packed):
        raise ValueError(f"Empty glyph U+{code:04X}")
    return bytes(packed)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, required=True)
    parser.add_argument(
        "--output-dir", type=Path,
        default=Path(__file__).resolve().parents[1] / "main",
    )
    args = parser.parse_args()
    if not args.font.is_file():
        parser.error(f"Source font does not exist: {args.font}")
    font = ImageFont.truetype(str(args.font), WIDTH * SCALE)
    # Noto's variable font permits a slightly stronger weight for tiny LCD text.
    try:
        axes = font.get_variation_axes()
    except OSError:
        axes = []
    if axes:
        values = [axis["default"] for axis in axes]
        for index, axis in enumerate(axes):
            name = axis["name"]
            if isinstance(name, bytes):
                name = name.decode("ascii", errors="replace")
            if name.lower() == "weight":
                values[index] = max(axis["minimum"], min(450, axis["maximum"]))
        font.set_variation_by_axes(values)

    codes = gb2312_han_codes()
    glyphs = [pack_glyph(font, code) for code in codes]
    data = b"".join(glyphs)
    assert len(data) == EXPECTED_COUNT * BYTES_PER_GLYPH
    assert all(codes[index] < codes[index + 1] for index in range(len(codes) - 1))
    # Validate the row-crossing bit layout independently of byte generation.
    for glyph in glyphs:
        unpacked = [bool(glyph[i // 8] & (0x80 >> (i % 8)))
                    for i in range(WIDTH * HEIGHT)]
        assert len(unpacked) == WIDTH * HEIGHT and any(unpacked)

    header = '''/* Generated Noto Sans SC Han subset, SIL OFL 1.1.
 * See assets/NotoSansSC-OFL.txt. Regenerate with tools/generate_ui_cjk.py.
 */
#pragma once
#include <stddef.h>
#include <stdint.h>

#define UI_CJK_WIDTH 12
#define UI_CJK_HEIGHT 16
#define UI_CJK_BYTES_PER_GLYPH 24

/* Unicode codes in ascending order. Glyph i starts at i * 24 bytes.
 * Pixels are continuous row-major bits, MSB first, with no row padding.
 */
extern const uint16_t ui_cjk_codes[];
extern const uint8_t ui_cjk_bits[];
extern const size_t ui_cjk_count;
'''
    digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
    output = [
        "/* Generated by tools/generate_ui_cjk.py; do not edit manually.",
        " * Noto Sans SC, SIL OFL 1.1; see assets/NotoSansSC-OFL.txt.",
        f" * Source font SHA-256: {digest}",
        f" * {EXPECTED_COUNT} Han glyphs, 12 x 16, 24 bytes per glyph; MSB first.",
        " */", '#include "ui_cjk.h"', "", "const uint16_t ui_cjk_codes[] = {",
    ]
    output.extend("    " + ", ".join(f"0x{code:04x}" for code in codes[i:i + 12]) + ","
                  for i in range(0, len(codes), 12))
    output.extend(["};", "", "const uint8_t ui_cjk_bits[] = {"])
    output.extend("    " + ",".join(f"0x{byte:02x}" for byte in glyph) + ","
                  for glyph in glyphs)
    output.extend([
        "};", "",
        "const size_t ui_cjk_count = sizeof(ui_cjk_codes) / sizeof(ui_cjk_codes[0]);",
        "",
    ])
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "ui_cjk.h").write_text(header, encoding="utf-8", newline="\n")
    (args.output_dir / "ui_cjk.c").write_text("\n".join(output), encoding="utf-8", newline="\n")
    print(f"Generated {len(codes)} sorted Unicode Han glyphs; "
          f"{len(data):,} bitmap bytes + {len(codes) * 2:,} index bytes.")
    print(f"Output: {args.output_dir / 'ui_cjk.h'}")
    print(f"Output: {args.output_dir / 'ui_cjk.c'}")


if __name__ == "__main__":
    main()
